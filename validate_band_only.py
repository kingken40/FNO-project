"""
Validates the band-only test data generated by
fno_frequency_dataset_v4_band_only.py.

The script checks the frequency modes present in a generated starting wave
to confirm that each band contains only its intended range:
control 17-24, middle 25-31, and high 32-48.

This provides a simple check that the band-only generator is working as
intended before the data is used for the FNO experiments.
"""
import numpy as np

# Load the small dataset generated
data = np.load(
    r"band_test_small\frequency_extension_dataset.npz"
)

# Take the first high band-only starting wave
u0 = data["X_test_band_high"][0, 0, :]

n = len(u0)
x = np.linspace(0, 1, n)

# Measure modes 1 through 60
coefficients = []

for k in range(1, 61):
    basis = np.sin(k * np.pi * x)

    coefficient = (
        2.0 / (n - 1)
    ) * np.sum(u0 * basis)

    coefficients.append(abs(coefficient))

# Show modes with a noticeable coefficient
for k, value in enumerate(coefficients, start=1):
    if value > 1e-4:
        print(f"Mode {k}: {value:.6f}")
